    public static (string EventContext, string WireContext, string Stats) Emit(
        IReadOnlyList<Assembly> domainAssemblies)
    {
        var persistableEvents = new SortedSet<string>(StringComparer.Ordinal);
        var wire = new SortedSet<string>(StringComparer.Ordinal);
        // Jede typisierte Id (Id<X>), die irgendein Typ der Anwendung trägt — Nachrichten, Zustände (Snapshots), Wertobjekte: je Ziel ein
        //   geschlossener IdJsonKonverter<X> in beiden Kontexten (der STJ-Quellgenerator kennt keine offenen generischen Konverter).
        var ids = new SortedSet<string>(StringComparer.Ordinal);
        var zustaende = new SortedSet<string>(StringComparer.Ordinal);

        // Es werden AUSSCHLIESSLICH die drei geladenen Domain-Assemblies durchsucht
        // (assembly.GetTypes() liefert nur die dort DEFINIERTEN Typen) — deckungsgleich zum
        // domainAssemblies-Filter der Roslyn-Variante. Interface-Zugehörigkeit per FullName
        // (MetadataLoadContext-Typen sind inspection-only). Nur die konkreten Klassen zählen,
        // Signale werden bewusst nicht registriert.
        foreach (var asm in domainAssemblies)
            foreach (var t in AlleTypen(asm))
                foreach (var p in t.GetProperties(BindingFlags.Public | BindingFlags.Instance | BindingFlags.DeclaredOnly))
                    SammleIds(p.PropertyType, ids);

        foreach (var asm in domainAssemblies)
        {
            foreach (var t in ConcreteClasses(asm))
            {
                var ifaces = t.GetInterfaces().Select(i => i.FullName).ToHashSet(StringComparer.Ordinal);
                var name = "global::" + FullyQualified(t);
                var isEvent = ifaces.Contains("Abstractions.IEvent");
                var isTransient = ifaces.Contains("Abstractions.ITransientEvent");
                var isCommand = ifaces.Contains("Abstractions.ICommand");
                var isWire = ifaces.Contains("Abstractions.IWireMessage");
                // Queries und Antworten: der JSON-Eingang der Werkbank (Infrastructure/Eingang) liest/schreibt sie über diesen Kontext.
                var isQuery = ifaces.Contains("Abstractions.IQuery") || ifaces.Contains("Abstractions.IQueryResponse");

                if (isEvent && !isTransient) persistableEvents.Add(name);
                if (isEvent || isCommand || isWire || isQuery) wire.Add(name);

                // Der Zustand einer Funktion (IZustand<T> im Konstruktor, Plan Pub/Sub-Neustrukturierung §2.9): gesichert über denselben Speicher-
                //   Kontext (GeneratedFunktionsBausteine koppelt Default.{T} zur Compile-Zeit).
                if (ifaces.Contains("Abstractions.IFunktion"))
                    foreach (var c in t.GetConstructors(BindingFlags.Public | BindingFlags.Instance))
                        foreach (var p in c.GetParameters())
                            if (p.ParameterType.IsGenericType && p.ParameterType.GetGenericTypeDefinition().FullName == Abstractions.Funktionsvertrag.Zustand)
                                zustaende.Add("global::" + FullyQualified(p.ParameterType.GetGenericArguments()[0]));

                // Schema-Evolution (IUpcast<TAlt, …>): die früheren Gestalten liegen als alte Bytes im Store — Marten liest sie über
                // denselben Kontext (GeneratedEventUpcasting koppelt Default.{TAlt} zur Compile-Zeit). Alle Typ-Argumente der Kante.
                foreach (var kante in t.GetInterfaces().Where(i => i.IsGenericType
                             && (i.GetGenericTypeDefinition().FullName ?? "").StartsWith("Abstractions.IUpcast`", StringComparison.Ordinal)))
                    foreach (var arg in kante.GetGenericArguments())
                        persistableEvents.Add("global::" + FullyQualified(arg));
            }
        }

        var konverter = string.Concat(ids.Select(z => $"        typeof({Abstractions.Idvertrag.Konverter(z)}),\n"));
        var eventCtx = Build(EventContextHeader.Replace("/*ID-KONVERTER*/\n", konverter), "EventJsonSerializerContext",
            persistableEvents.Concat(zustaende).Distinct(StringComparer.Ordinal), "Domänen-Events (Domain.*, persistierbar) und Zustände der Funktionen (IZustand<T>)");
        var wireCtx = Build(WireContextHeader.Replace("/*ID-KONVERTER*/\n", konverter), "CqrsWireJsonContext", wire,
            "Domänen-Commands/Events/Queries (Domain.*)");

        static int Framework(string kopf) => kopf.Split("[JsonSerializable(").Length - 1;
        var stats = $"Storage-Events: {persistableEvents.Count + Framework(EventContextHeader)} ({Framework(EventContextHeader)} Framework), Zustände: {zustaende.Count}, "
                    + $"Wire-Typen: {wire.Count + Framework(WireContextHeader)} ({Framework(WireContextHeader)} Framework), Id-Konverter: {ids.Count}";
        return (eventCtx, wireCtx, stats);
    }

    private static string Build(string header, string className, IEnumerable<string> domainTypes, string sectionNote)
    {
        var sb = new StringBuilder();
        sb.Append(header);
        sb.AppendLine();
        sb.AppendLine($"// ── {sectionNote} (gescannt) ──");
        foreach (var t in domainTypes)
            sb.AppendLine($"[JsonSerializable(typeof({t}))]");
        sb.AppendLine($"public partial class {className} : JsonSerializerContext");
        sb.AppendLine("{");
        sb.AppendLine("}");
        return sb.ToString();
    }

    /// <summary>Sammelt die Ziel-Typen jeder <c>Id&lt;X&gt;</c> in <paramref name="t"/> — auch in Listen, Arrays, Wörterbüchern und Nullable.</summary>
    private static void SammleIds(Type t, ISet<string> ids)
    {
        if (t.IsArray) { SammleIds(t.GetElementType()!, ids); return; }
        if (!t.IsGenericType || t.IsGenericTypeDefinition) return;
        var args = t.GetGenericArguments();
        if (t.GetGenericTypeDefinition().FullName == Abstractions.Idvertrag.IdMetadatenName)
        {
            ids.Add(FullyQualified(args[0]));
            return;
        }
        foreach (var a in args) SammleIds(a, ids);
    }

    private static IEnumerable<Type> AlleTypen(Assembly assembly)
    {
        Type?[] types;
        try { types = assembly.GetTypes(); }
        catch (ReflectionTypeLoadException ex) { types = ex.Types; }
        return types.Where(t => t is not null)!;
    }

    // Konkrete Klassen (keine Structs/Enums/Interfaces, nicht abstrakt, nicht statisch).
    // Statische Klassen sind in Reflection abstract+sealed → durch !IsAbstract ausgeschlossen.
    private static IEnumerable<Type> ConcreteClasses(Assembly assembly)
    {
        Type?[] types;
        try
        {
            types = assembly.GetTypes();
        }
        catch (ReflectionTypeLoadException ex)
        {
            types = ex.Types;
        }

        foreach (var t in types)
        {
            if (t is null) continue;
            if (t.IsClass && !t.IsAbstract)
                yield return t;
        }
    }

    /// <summary>Voll namespace-qualifizierter Name mit '.'-getrennten geschachtelten Typen (ohne global::).</summary>
    private static string FullyQualified(Type t)
    {
        var name = t.Name;
        var tick = name.IndexOf('`');
        if (tick >= 0)
            name = name.Substring(0, tick);

        if (t.IsNested && t.DeclaringType != null)
            return FullyQualified(t.DeclaringType) + "." + name;

        return string.IsNullOrEmpty(t.Namespace) ? name : t.Namespace + "." + name;
    }
}
