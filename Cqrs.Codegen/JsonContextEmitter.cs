        // <auto-generated/> — erzeugt vom Cqrs.Codegen-Prepass. NICHT von Hand ändern.
        // FRAMEWORK-Kopf (stabil) + gescannte Domänen-Events. Siehe JsonContextEmitter.
        #nullable enable
        using System.Text.Json.Serialization;
        using Infrastructure.Aggregate;

        namespace Infrastructure.Serialization;

        /// <summary>
        /// STJ-Manifest über ALLE persistierbaren Events (Marten-STORAGE). Metadata-Mode: kombinierbar mit
        /// Martens JsonSerializerOptions + Resolver-Chain. Der EventJsonGenerator koppelt die Menge zur
        /// Compile-Zeit (Default.{Event}).
        /// </summary>
        [JsonSourceGenerationOptions(
            GenerationMode = JsonSourceGenerationMode.Metadata,
            Converters = new System.Type[]
            {
                // Der Command einer Frist (FristGesetzt, Plan Pub/Sub-Neustrukturierung Phase 3) — über die generierten Tabellen, ohne Reflection.
                typeof(ICommandJsonConverter),
        /*ID-KONVERTER*/
            })]
        // ── Framework: Aggregat-Inbox (IEvent → persistiert) ──
        [JsonSerializable(typeof(KommandoVerarbeitet))]
        [JsonSerializable(typeof(KommandoAbgelehnt))]
        // ── Framework: festgehaltene Ausgabe der Funktionen (Plan Pub/Sub-Neustrukturierung Phase 3) ──
        [JsonSerializable(typeof(Infrastructure.Funktionen.BefehlFestgehalten))]
        [JsonSerializable(typeof(Infrastructure.Funktionen.AusgabeFestgehalten))]
