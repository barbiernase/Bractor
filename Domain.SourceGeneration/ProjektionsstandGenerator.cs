using System.Linq;
using System.Text;
using Infrastructure.SourceGeneration;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace Domain.SourceGeneration;

/// <summary>
/// Der Code-Stand jeder Projektion (Hash ihrer normalisierten Syntax, <see cref="Kodeform"/>) als Assembly-Angabe
/// <c>[assembly: Projektionsstand(typeof(P), "…")]</c> — nur in der Compilation der Projektion ist ihr Quelltext sichtbar. Die Komposition liest die
/// Angabe über Roslyn (PullPathGenerator) und trägt sie in den Stand der Leseseite ein: ändert sich der Code, baut eine Sim-Umgebung neu auf.
/// Die Projektion selbst bleibt unberührt (kein <c>partial</c> nötig).
/// </summary>
[Generator]
public sealed class ProjektionsstandGenerator : IIncrementalGenerator
{
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var projektionen = context.SyntaxProvider
            .CreateSyntaxProvider(
                predicate: static (s, _) => s is ClassDeclarationSyntax { BaseList: not null },
                transform: static (ctx, _) => ctx.SemanticModel.GetDeclaredSymbol((ClassDeclarationSyntax)ctx.Node) is INamedTypeSymbol t
                                              && Projektionsform.IstProjektion(t)
                    ? (t.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat), Kodeform.Hash(t))
                    : default)
            .Where(static x => x.Item1 != null)
            .Collect();

        context.RegisterSourceOutput(projektionen, static (spc, alle) =>
        {
            if (alle.Length == 0) return;
            var sb = new StringBuilder();
            sb.AppendLine("// <auto-generated/> — der Code-Stand der Projektionen (ProjektionsstandGenerator).");
            foreach (var (typ, hash) in alle.Distinct().OrderBy(x => x.Item1, System.StringComparer.Ordinal))
                sb.AppendLine($"[assembly: global::Abstractions.ProjektionsstandAttribute(typeof({typ}), \"{hash}\")]");
            spc.AddSource("Projektionsstand.g.cs", sb.ToString());
        });
    }
}
