using System.Linq;
using System.Text;
using Infrastructure.SourceGeneration;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace Domain.SourceGeneration;

/// <summary>
/// Ein Read-Model, das ein Aggregat abbildet, trägt dessen typisierte Id (<c>Id&lt;T&gt; Id</c>, docs/10 §10.4). Ein Store, der
/// einen einfachen Schlüssel braucht (Marten kann <c>Id&lt;T&gt;</c> nicht als Dokument-Identität — sein Codegen bricht an generischen Ids), bekommt
/// dafür eine generierte Speicher-Identität: <c>Schluessel</c>, dieselbe UUID, beim Setzen zurück in <c>Id</c>. Der Fachcode sieht und setzt nur
/// <c>Id</c>.
///
/// CQRS111 — ein solches Read-Model ist nicht <c>partial</c>: dann kann der Generator den Schlüssel nicht ergänzen.
/// </summary>
[Generator]
public sealed class ReadModelSchluesselGenerator : IIncrementalGenerator
{
    public const string NichtPartialId = "CQRS111";

    private const string Schluessel = Abstractions.Projektionsvertrag.Schluessel;

    private static readonly DiagnosticDescriptor NichtPartial = new(
        NichtPartialId, "Read-Model mit typisierter Id ist nicht partial",
        "'{0}' hat eine typisierte Id (Id<{1}> Id) — als partial deklarieren, damit der Generator die Speicher-Identität ergänzt",
        "CQRS.Leseseite", DiagnosticSeverity.Error, isEnabledByDefault: true);

    private sealed class Modell
    {
        public Modell(string ns, string name, string art, string? fehler, Location? ort, string ziel)
        { Namespace = ns; Name = name; Art = art; Fehler = fehler; Ort = ort; Ziel = ziel; }
        public string Namespace { get; }
        public string Name { get; }
        public string Art { get; }
        public string? Fehler { get; }
        public Location? Ort { get; }
        public string Ziel { get; }
    }

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var modelle = context.SyntaxProvider
            .CreateSyntaxProvider(
                predicate: static (s, _) => s is TypeDeclarationSyntax { BaseList: not null } and (ClassDeclarationSyntax or RecordDeclarationSyntax),
                transform: static (ctx, _) => Lies((TypeDeclarationSyntax)ctx.Node, ctx.SemanticModel))
            .Where(static m => m is not null)
            .Collect();

        context.RegisterSourceOutput(modelle, static (spc, alle) =>
        {
            foreach (var m in alle.Where(m => m != null).Cast<Modell>().GroupBy(m => m.Namespace + "." + m.Name).Select(g => g.First()))
            {
                if (m.Fehler != null)
                {
                    spc.ReportDiagnostic(Diagnostic.Create(NichtPartial, m.Ort, m.Name, m.Ziel));
                    continue;
                }
                var sb = new StringBuilder();
                sb.AppendLine("// <auto-generated/> — Speicher-Identität eines Read-Models mit typisierter Id (ReadModelSchluesselGenerator).");
                if (m.Namespace.Length > 0) sb.AppendLine($"namespace {m.Namespace};");
                sb.AppendLine();
                sb.AppendLine($"partial {m.Art} {m.Name}");
                sb.AppendLine("{");
                sb.AppendLine("    /// <summary>Die Id als UUID — für Stores, die einen einfachen Schlüssel brauchen. Der Fachcode nutzt <c>Id</c>.</summary>");
                sb.AppendLine("    [global::System.ComponentModel.EditorBrowsable(global::System.ComponentModel.EditorBrowsableState.Never)]");
                sb.AppendLine($"    public global::System.Guid {Schluessel} {{ get => Id.Wert; init => Id = new(value); }}");
                sb.AppendLine("}");
                spc.AddSource($"{m.Namespace}.{m.Name}.Schluessel.g.cs", sb.ToString());
            }
        });
    }

    private static Modell? Lies(TypeDeclarationSyntax d, SemanticModel sm)
    {
        if (sm.GetDeclaredSymbol(d) is not INamedTypeSymbol t || t.ContainingType != null || t.IsGenericType) return null;
        if (!t.AllInterfaces.Any(i => Projektionsform.Name(i) == "Abstractions.IReadModel")) return null;
        var id = t.GetMembers("Id").OfType<IPropertySymbol>().FirstOrDefault();
        if (id == null || !Projektionsform.IstId(id.Type)) return null;
        // Nur die erste Deklaration eines partial-Typs berichtet.
        if (t.DeclaringSyntaxReferences.FirstOrDefault()?.GetSyntax() != d) return null;
        var ziel = ((INamedTypeSymbol)id.Type).TypeArguments[0].Name;
        var art = t.IsRecord ? (t.TypeKind == TypeKind.Struct ? "record struct" : "record") : (t.TypeKind == TypeKind.Struct ? "struct" : "class");
        var partial = t.DeclaringSyntaxReferences.Select(r => r.GetSyntax()).OfType<TypeDeclarationSyntax>()
            .Any(x => x.Modifiers.Any(m => m.IsKind(SyntaxKind.PartialKeyword)));
        return new Modell(t.ContainingNamespace.IsGlobalNamespace ? "" : t.ContainingNamespace.ToDisplayString(), t.Name, art,
            partial ? null : "nicht partial", d.Identifier.GetLocation(), ziel);
    }
}
