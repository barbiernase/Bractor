using Microsoft.CodeAnalysis;
using System.Collections.Generic;
using System.Linq;
using System.Text;

namespace Infrastructure.SourceGeneration
{
    /// <summary>
    /// QUELLEN als Treiber + Konfig (docs/konzept-werkbank.md §3.3): findet jeden Quellen-Typ — einen Record, der von einer
    /// Treiber-Basis erbt (<see cref="Abstractions.Treibervertrag"/>, z. B. <c>sealed record DateiErkannt : DateiGemeldet;</c>) — und
    /// erzeugt <c>GeneratedQuellen.Alle</c>: je Quelle Typ, Treiber, Konfig-Abschnitt (= Typname), Wirker-Id und eine Fabrik
    /// <c>daten =&gt; new DateiErkannt { … }</c>, damit der Treiber ohne Reflection baut (Inv. 4). Die Form prüft CQRS070 in der Domäne.
    /// </summary>
    [Generator]
    public class QuellenGenerator : ISourceGenerator
    {
        public void Initialize(GeneratorInitializationContext context) { }

        public void Execute(GeneratorExecutionContext context)
        {
            var c = context.Compilation;
            // Nur die Laufzeit (sie kennt QuellEingang/DateiDaten) bekommt die Tabelle.
            if (c.GetTypeByMetadataName("Infrastructure.Quellen.QuellEingang") == null) return;
            var dateiBasis = c.GetTypeByMetadataName(Abstractions.Treibervertrag.DateiBasis);
            if (dateiBasis == null) return;

            var alle = new List<INamedTypeSymbol>();
            Sammle(c.GlobalNamespace, alle);
            var quellen = alle
                .Where(t => t.TypeKind == TypeKind.Class && !t.IsAbstract && ErbtVon(t, dateiBasis))
                .OrderBy(t => t.ToDisplayString(), System.StringComparer.Ordinal)
                .ToList();

            var fq = SymbolDisplayFormat.FullyQualifiedFormat;
            var sb = new StringBuilder();
            sb.AppendLine("// <auto-generated/> QuellenGenerator — je Quellen-Typ Treiber, Konfig-Abschnitt, Wirker-Id und Fabrik (keine Reflection).");
            sb.AppendLine("#nullable enable");
            sb.AppendLine("namespace Infrastructure.Quellen");
            sb.AppendLine("{");
            sb.AppendLine("    public static class GeneratedQuellen");
            sb.AppendLine("    {");
            sb.AppendLine("        public static readonly global::System.Collections.Generic.IReadOnlyList<QuellTyp> Alle = new QuellTyp[]");
            sb.AppendLine("        {");
            foreach (var q in quellen)
            {
                var name = q.Name;
                sb.AppendLine($"            new QuellTyp(typeof({q.ToDisplayString(fq)}), \"{Abstractions.Treibervertrag.Datei}\", \"{name}\", \"quelle:{name}\",");
                sb.AppendLine($"                d => new {q.ToDisplayString(fq)} {{ Name = d.Name, Pfad = d.Pfad, RelativerPfad = d.RelativerPfad, Groesse = d.Groesse, "
                    + "GeaendertAm = d.GeaendertAm, ErkanntAm = d.ErkanntAm, Kennung = d.Kennung }),");
            }
            sb.AppendLine("        };");
            sb.AppendLine("    }");
            sb.AppendLine("}");
            context.AddSource("GeneratedQuellen.g.cs", sb.ToString());
        }

        private static bool ErbtVon(INamedTypeSymbol t, INamedTypeSymbol basis)
        {
            for (var b = t.BaseType; b != null; b = b.BaseType)
                if (SymbolEqualityComparer.Default.Equals(b, basis)) return true;
            return false;
        }

        private static void Sammle(INamespaceSymbol ns, List<INamedTypeSymbol> aus)
        {
            foreach (var t in ns.GetTypeMembers()) aus.Add(t);
            foreach (var sub in ns.GetNamespaceMembers())
            {
                var n = sub.Name;
                if (ns.IsGlobalNamespace && (n == "System" || n == "Microsoft" || n == "Marten" || n == "Proto" || n == "Npgsql"
                        || n == "JasperFx" || n == "Google" || n == "Grpc" || n == "StackExchange" || n == "Weasel")) continue;
                Sammle(sub, aus);
            }
        }
    }
}
