using Microsoft.CodeAnalysis;
using System.Collections.Generic;
using System.Linq;
using System.Text;

namespace Infrastructure.SourceGeneration
{
    /// <summary>
    /// Der Query-Dienst der Leseseite (Plan Pub/Sub-Neustrukturierung §2.5, §3.3, Phase 8), generiert in der Komposition: je Query die
    /// <c>Frage</c> eines Readers (<c>IReader</c>, gelesen über <see cref="Projektionsform"/>) mit ihren Lese-Fähigkeiten aus einem Bereich.
    /// Was die Antwort zeigt, findet der Generator selbst — kein <c>ctx.Track</c>:
    /// <list type="bullet">
    ///   <item>die <b>gezeigten Ids</b>: jedes <c>Id&lt;T&gt;</c>-Feld der Antwort (auch in Listen und geschachtelten Typen) und der Query, nach der
    ///     gefragt wurde (die Antwort hängt von ihr ab, auch wenn sie sie nicht wiederholt), dazu die Streams aus „mindestens S auf v“;</item>
    ///   <item>die <b>Projektionen dahinter</b>: die, die in einen Store schreiben, dessen Lese-Fähigkeit die Frage nimmt.</item>
    /// </list>
    /// Vor dem Reader wartet der Dienst begrenzt auf „mindestens S auf v“ (Read-your-writes), danach hängt er den Stand je gezeigter Id an
    /// (<c>ProjektionsStaende</c>: Guard + Log, über mehrere Projektionen der kleinste).
    /// Eine Query, deren Ziel ein Aggregat ist (<c>Frage</c> im Decider, §2.6), geht über <c>AggregatAbfrage</c> an den Aggregat-Actor der Id aus
    /// ihrem Glied <c>Id&lt;TAggregat&gt;</c>; die Antwort zeigt genau dieses Aggregat mit der Version, auf der es antwortete — exakt, ohne Warten.
    /// </summary>
    [Generator]
    public class QueryDienstGenerator : ISourceGenerator
    {
        public void Initialize(GeneratorInitializationContext context) { }

        public void Execute(GeneratorExecutionContext context)
        {
            if (!Laufzeitprojekt.Ist(context.Compilation)) return;
            var bild = Leseseitenbild.Lies(context.Compilation);
            var reader = bild.Reader.Where(r => r.Fehler.Count == 0 && r.Doppelt.Count == 0).ToList();
            var aggregate = bild.Aggregate.Where(a => a.Fehler.Count == 0 && a.Doppelt.Count == 0).ToList();
            context.AddSource("GeneratedQueryDienst.g.cs", Emit(bild, reader, aggregate));
        }

        private static string Fq(ITypeSymbol t) => t.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);

        private static string Feld(Projektionsform.Reader r) => "_" + char.ToLowerInvariant(r.Typ.Name[0]) + r.Typ.Name.Substring(1);

        private static string Emit(Leseseitenbild bild, List<Projektionsform.Reader> reader, List<Projektionsform.Aggregatfragen> aggregate)
        {
            var ids = new IdSammler();
            var sb = new StringBuilder();
            sb.AppendLine("// <auto-generated/>");
            sb.AppendLine("// Der Query-Dienst der Leseseite (QueryDienstGenerator).");
            sb.AppendLine("#nullable enable");
            sb.AppendLine("using Abstractions;");
            sb.AppendLine("using Infrastructure.Projections;");
            sb.AppendLine("using Microsoft.Extensions.DependencyInjection;");
            sb.AppendLine("using System;");
            sb.AppendLine("using System.Collections.Generic;");
            sb.AppendLine("using System.Threading;");
            sb.AppendLine("using System.Threading.Tasks;");
            sb.AppendLine();
            sb.AppendLine("namespace Infrastructure.Projections.Generated;");
            sb.AppendLine();
            sb.AppendLine("public sealed class GeneratedQueryDienst : IQueryDienst");
            sb.AppendLine("{");
            sb.AppendLine("    /// <summary>Wie lange eine Query höchstens auf „mindestens S auf v“ wartet (Read-your-writes), bevor sie „noch nicht so weit“ antwortet.</summary>");
            sb.AppendLine("    public static readonly TimeSpan MindestensFrist = TimeSpan.FromSeconds(3);");
            sb.AppendLine();
            sb.AppendLine("    public static IReadOnlyList<Type> SupportedQueryTypes { get; } = new Type[]");
            sb.AppendLine("    {");
            foreach (var f in reader.SelectMany(r => r.Fragen).Concat(aggregate.SelectMany(a => a.Fragen))) sb.AppendLine($"        typeof({Fq(f.Query)}),");
            sb.AppendLine("    };");
            sb.AppendLine();
            sb.AppendLine("    IReadOnlyList<Type> IQueryDienst.QueryTypen => SupportedQueryTypes;");
            sb.AppendLine();
            foreach (var r in reader) sb.AppendLine($"    private readonly {Fq(r.Typ)} {Feld(r)};");
            sb.AppendLine("    private readonly IFaehigkeitsFabrik _faehigkeiten;");
            sb.AppendLine("    private readonly ProjektionsStaende? _staende;");
            if (aggregate.Count > 0) sb.AppendLine("    private readonly global::Infrastructure.Aggregate.ActorSystem.AggregatAbfrage _aggregate;");
            sb.AppendLine();
            sb.AppendLine("    public GeneratedQueryDienst(IServiceProvider provider)");
            sb.AppendLine("    {");
            foreach (var r in reader) sb.AppendLine($"        {Feld(r)} = {PullPathGenerator.Konstruktion(r.Typ, "provider")};");
            sb.AppendLine("        _faehigkeiten = provider.GetRequiredService<IFaehigkeitsFabrik>();");
            sb.AppendLine("        _staende = provider.GetService<ProjektionsStaende>();");
            if (aggregate.Count > 0) sb.AppendLine("        _aggregate = provider.GetRequiredService<global::Infrastructure.Aggregate.ActorSystem.AggregatAbfrage>();");
            sb.AppendLine("    }");
            sb.AppendLine();

            // Die Projektionen je Frage (als Felder: eine Liste je Frage, einmal angelegt).
            var nr = 0;
            var listen = new Dictionary<Projektionsform.Frage, string>();
            foreach (var f in reader.SelectMany(r => r.Fragen))
            {
                var name = "_hinter" + (nr++);
                listen[f] = name;
                var kennungen = bild.Hinter(f).Select(p => "\"" + Abstractions.Projektionsvertrag.Kennung(p.Typ.Name) + "\"");
                sb.AppendLine($"    private static readonly string[] {name} = {{ {string.Join(", ", kennungen)} }};   // {f.Query.Name}");
            }
            sb.AppendLine();

            sb.AppendLine("    public Task<QueryResponse<IQueryResponse>> ExecuteAsync(IQuery query, IReadOnlyList<StreamStand>? mindestens = null)");
            sb.AppendLine("    {");
            sb.AppendLine("        ArgumentNullException.ThrowIfNull(query);");
            sb.AppendLine("        switch (query)");
            sb.AppendLine("        {");
            foreach (var r in reader)
                foreach (var f in r.Fragen)
                {
                    var args = f.Parameter.Select(x => x.Art switch
                    {
                        "q" => "q",
                        "ct" => "CancellationToken.None",
                        _ => $"b.Hole<{Fq(x.Typ!)}>()",
                    });
                    var aufruf = $"{Feld(r)}.{Abstractions.Projektionsvertrag.Frage}({string.Join(", ", args)})";
                    var warte = f.Huelle != "" ? "await " : "";
                    var wert = f.OneOf ? $"({warte}{aufruf}).Value" : $"{warte}{aufruf}";
                    var lambdaAsync = f.Huelle != "" ? "async " : "";
                    var ergebnis = f.Huelle != "" ? $"(IQueryResponse){wert}" : $"Task.FromResult((IQueryResponse){wert})";
                    sb.AppendLine($"            case {Fq(f.Query)} q:");
                    sb.AppendLine($"                return FrageAsync({listen[f]}, mindestens, {lambdaAsync}b => {ergebnis},");
                    sb.AppendLine($"                    (a, ids) => {{ {ids.Aufruf(f.Query, "q")} {AntwortIds(ids, f)} }});");
                }
            // Eine Query an ein Aggregat (§2.6): an die Identität aus ihrem Glied Id<TAggregat> — der Stand ist exakt, „mindestens S auf v“ gilt von selbst.
            foreach (var a in aggregate)
                foreach (var f in a.Fragen)
                {
                    sb.AppendLine($"            case {Fq(f.Query)} q:   // Frage an das Aggregat {a.State.Name}");
                    sb.AppendLine($"                return _aggregate.FrageAsync(q.{f.IdGlied}.Wert, \"{CommandAggregateMapGenerator.AggregatIdentität(a.State)}\", q);");
                }
            sb.AppendLine("            default:");
            sb.AppendLine("                throw new NotSupportedException($\"Keine Frage für die Query {query.GetType().Name}.\");");
            sb.AppendLine("        }");
            sb.AppendLine("    }");
            sb.AppendLine();
            sb.AppendLine("    private async Task<QueryResponse<IQueryResponse>> FrageAsync(string[] projektionen, IReadOnlyList<StreamStand>? mindestens,");
            sb.AppendLine("        Func<IFaehigkeiten, Task<IQueryResponse>> frage, Action<IQueryResponse, List<Guid>> gezeigt)");
            sb.AppendLine("    {");
            sb.AppendLine("        // Read-your-writes: erst lesen, wenn die Projektionen die eigenen Writes des Clients verarbeitet haben (begrenzt).");
            sb.AppendLine("        var nochNicht = mindestens is { Count: > 0 } && _staende != null");
            sb.AppendLine("            && !await _staende.WarteAsync(projektionen, mindestens, MindestensFrist);");
            sb.AppendLine("        IQueryResponse data;");
            sb.AppendLine("        // Ein Fähigkeits-Bereich je Query: die Store-Funktionen, die die Frage als Parameter verlangt.");
            sb.AppendLine("        using (var bereich = _faehigkeiten.Oeffne())");
            sb.AppendLine("            data = await frage(bereich);");
            sb.AppendLine("        // Was die Antwort zeigt: ihre Ids, die der Query und die geschriebenen Streams (auch wenn ein Objekt nicht ins Ergebnis fällt).");
            sb.AppendLine("        var ids = new List<Guid>();");
            sb.AppendLine("        gezeigt(data, ids);");
            sb.AppendLine("        if (mindestens != null) foreach (var m in mindestens) ids.Add(m.Stream);");
            sb.AppendLine("        var deps = _staende is null ? null : await _staende.LiesAsync(projektionen, ids);");
            sb.AppendLine("        return new QueryResponse<IQueryResponse> { Data = data, Deps = deps, NochNicht = nochNicht, Projektionen = projektionen };");
            sb.AppendLine("    }");
            sb.AppendLine();
            ids.Emit(sb);
            sb.AppendLine("}");
            return sb.ToString();
        }

        private static string AntwortIds(IdSammler ids, Projektionsform.Frage f)
        {
            var faelle = f.Antworten.Where(ids.Enthaelt).Select(a => $"case {Fq(a)} x: {ids.Aufruf(a, "x")} break;").ToList();
            return faelle.Count == 0 ? "" : $"switch (a) {{ {string.Join(" ", faelle)} }}";
        }

        /// <summary>
        /// Erzeugt je Typ, der (auch geschachtelt) eine <c>Id&lt;T&gt;</c> enthält, eine Methode, die ihre Werte sammelt — ohne Reflection, aus den
        /// Gliedern zur Build-Zeit.
        /// </summary>
        private sealed class IdSammler
        {
            private readonly Dictionary<string, (INamedTypeSymbol Typ, string Methode)> _methoden = new Dictionary<string, (INamedTypeSymbol, string)>();
            private readonly Dictionary<string, bool> _enthaelt = new Dictionary<string, bool>();

            /// <summary>Enthält der Typ (auch geschachtelt) eine Id?</summary>
            public bool Enthaelt(ITypeSymbol t) => t is INamedTypeSymbol n && Projektionsform.Durchsuchbar(n) && Enthaelt(n, new HashSet<string>());

            private bool Enthaelt(INamedTypeSymbol t, HashSet<string> unterwegs)
            {
                var key = t.ToDisplayString();
                if (_enthaelt.TryGetValue(key, out var e)) return e;
                if (!unterwegs.Add(key)) return false;
                var ja = false;
                foreach (var (_, typ) in Projektionsform.Glieder(t))
                {
                    var inner = Kern(typ);
                    if (Projektionsform.IstId(inner)) { ja = true; break; }
                    if (Projektionsform.Element(inner) is { } el && (Projektionsform.IstId(Kern(el)) || Durchsuchbar(Kern(el), unterwegs))) { ja = true; break; }
                    if (Durchsuchbar(inner, unterwegs)) { ja = true; break; }
                }
                unterwegs.Remove(key);
                _enthaelt[key] = ja;
                return ja;
            }

            private bool Durchsuchbar(ITypeSymbol t, HashSet<string> unterwegs) =>
                t is INamedTypeSymbol n && Projektionsform.Durchsuchbar(n) && Enthaelt(n, unterwegs);

            /// <summary><c>T?</c> (Nullable-Struktur) → <c>T</c>.</summary>
            private static ITypeSymbol Kern(ITypeSymbol t) =>
                t is INamedTypeSymbol n && n.IsGenericType && Projektionsform.Name(n) == "System.Nullable`1" ? n.TypeArguments[0] : t;

            private static bool IstNullable(ITypeSymbol t) => t is INamedTypeSymbol n && n.IsGenericType && Projektionsform.Name(n) == "System.Nullable`1";

            /// <summary>Der Aufruf, der die Ids von <paramref name="ausdruck"/> (Typ <paramref name="t"/>) sammelt — leer, wenn er keine enthält.</summary>
            public string Aufruf(ITypeSymbol t, string ausdruck)
            {
                if (!Enthaelt(t)) return "";
                return Methode((INamedTypeSymbol)t) + "(" + ausdruck + ", ids);";
            }

            private string Methode(INamedTypeSymbol t)
            {
                var key = t.ToDisplayString();
                if (!_methoden.TryGetValue(key, out var m))
                {
                    m = (t, "Ids" + _methoden.Count);
                    _methoden[key] = m;
                }
                return m.Methode;
            }

            public void Emit(StringBuilder sb)
            {
                // Methoden entstehen beim Emittieren weiterer (geschachtelte Typen) — bis keine neue mehr dazukommt.
                var fertig = new HashSet<string>();
                while (_methoden.Keys.Any(k => !fertig.Contains(k)))
                {
                    foreach (var key in _methoden.Keys.Where(k => !fertig.Contains(k)).ToList())
                    {
                        fertig.Add(key);
                        var (t, name) = _methoden[key];
                        sb.AppendLine($"    private static void {name}({Fq(t)} x, List<Guid> ids)");
                        sb.AppendLine("    {");
                        if (t.IsReferenceType) sb.AppendLine("        if (x is null) return;");
                        foreach (var (glied, typ) in Projektionsform.Glieder(t))
                        {
                            var inner = Kern(typ);
                            var nullbar = typ.IsReferenceType || IstNullable(typ);
                            if (Projektionsform.IstId(inner))
                                sb.AppendLine(IstNullable(typ) ? $"        if (x.{glied} is {{ }} v_{glied}) ids.Add(v_{glied}.Wert);" : $"        ids.Add(x.{glied}.Wert);");
                            else if (Projektionsform.Element(inner) is { } el && (Projektionsform.IstId(Kern(el)) || Enthaelt(Kern(el))))
                            {
                                var elKern = Kern(el);
                                var rumpf = Projektionsform.IstId(elKern)
                                    ? (IstNullable(el) ? "if (v is { } w) ids.Add(w.Wert);" : "ids.Add(v.Wert);")
                                    : (IstNullable(el) ? $"if (v is {{ }} w) {Methode((INamedTypeSymbol)elKern)}(w, ids);" : $"{Methode((INamedTypeSymbol)elKern)}(v, ids);");
                                sb.AppendLine($"        {(nullbar ? $"if (x.{glied} is not null) " : "")}foreach (var v in x.{glied}) {{ {rumpf} }}");
                            }
                            else if (Enthaelt(inner))
                                sb.AppendLine(IstNullable(typ)
                                    ? $"        if (x.{glied} is {{ }} v_{glied}) {Methode((INamedTypeSymbol)inner)}(v_{glied}, ids);"
                                    : $"        {Methode((INamedTypeSymbol)inner)}(x.{glied}, ids);");
                        }
                        sb.AppendLine("    }");
                        sb.AppendLine();
                    }
                }
            }
        }
    }
}
