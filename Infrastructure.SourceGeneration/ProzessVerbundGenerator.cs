using System.Collections.Generic;
using System.Linq;
using System.Text;
using Abstractions;
using Microsoft.CodeAnalysis;

namespace Infrastructure.SourceGeneration
{
    /// <summary>
    /// Der VERBUND aller Prozess-Registries (docs/04 §4.5, docs/07): je Domänen-Assembly emittiert der <c>ProzessRegelnGenerator</c>
    /// <c>{Assembly}.Prozess.GeneratedProzessRegeln</c> (<see cref="Projektstruktur.ProzessNamespace"/>); die Laufzeit vereinigt sie hier
    /// zu <c>Infrastructure.Prozess.GeneratedProzessVerbund.Alle</c> — ohne eine getippte Liste von Assemblies.
    /// <list type="bullet">
    /// <item>CQRS099 — eine referenzierte Assembly deklariert Prozesse oder Flüsse, hat aber keine Registry (der Domänen-Generator läuft
    ///   dort nicht): sie würden still nie registriert.</item>
    /// <item>CQRS012 — derselbe Prozess-Name in zwei Assemblies (innerhalb einer Assembly prüft es der <c>ProzessRegelnGenerator</c>).</item>
    /// </list>
    /// </summary>
    [Generator]
    public class ProzessVerbundGenerator : ISourceGenerator
    {
        private static readonly DiagnosticDescriptor OhneRegistry = new DiagnosticDescriptor("CQRS099", "Prozesse ohne Registry",
            "Die Assembly '{0}' deklariert Prozesse/Flüsse ({1}), hat aber keine {2}.{3} — der Domänen-Generator (Domain.SourceGeneration) "
            + "läuft dort nicht; die Prozesse würden still nie registriert (docs/07)",
            "Cqrs", DiagnosticSeverity.Error, isEnabledByDefault: true);

        private static readonly DiagnosticDescriptor Kollision = new DiagnosticDescriptor("CQRS012", "Zwei Prozesse mit gleichem Namen",
            "Der Prozess-Name '{0}' ist mehrdeutig — er wird in mehreren Assemblies belegt ({1}). Gib mindestens einer Definition ein "
            + "explizites [ProzessName(\"...\")].",
            "Cqrs", DiagnosticSeverity.Error, isEnabledByDefault: true);

        public void Initialize(GeneratorInitializationContext context) { }

        public void Execute(GeneratorExecutionContext context)
        {
            var c = context.Compilation;
            // Nur die Laufzeit bekommt den Verbund.
            if (!Laufzeitprojekt.Ist(c)) return;
            var iDef = c.GetTypeByMetadataName("Abstractions.IProzessDefinition");
            var iPipeline = c.GetTypeByMetadataName("Abstractions.IPipeline");
            if (iDef == null) return;

            var registries = new List<string>();
            var namen = new Dictionary<string, List<string>>();
            var vertrag = iDef.ContainingAssembly;
            // Nur Assemblies, die den Vertrag referenzieren (Domäne) — Framework-Bibliotheken wie Marten werden nicht durchlaufen.
            foreach (var asm in c.SourceModule.ReferencedAssemblySymbols
                         .Where(a => a.Modules.Any(m => m.ReferencedAssemblies.Any(r => r.Name == vertrag.Name)))
                         .OrderBy(a => a.Name, System.StringComparer.Ordinal))
            {
                var defs = new List<INamedTypeSymbol>();
                Sammle(asm.GlobalNamespace, asm, defs);
                defs = defs.Where(t => t.TypeKind == TypeKind.Class && !t.IsAbstract && t.DeclaredAccessibility == Accessibility.Public
                    && (t.AllInterfaces.Contains(iDef, SymbolEqualityComparer.Default)
                        || (iPipeline != null && t.AllInterfaces.Contains(iPipeline, SymbolEqualityComparer.Default)))).ToList();
                var ns = Projektstruktur.ProzessNamespace(asm.Name);
                var registry = asm.GetTypeByMetadataName(ns + "." + Projektstruktur.ProzessRegistry);
                if (registry != null) registries.Add("global::" + ns + "." + Projektstruktur.ProzessRegistry);
                if (defs.Count == 0) continue;
                if (registry == null)
                {
                    context.ReportDiagnostic(Diagnostic.Create(OhneRegistry, Location.None, asm.Name,
                        string.Join(", ", defs.Select(d => d.Name)), ns, Projektstruktur.ProzessRegistry));
                    continue;
                }
                foreach (var d in defs)
                {
                    var name = Name(d);
                    if (!namen.TryGetValue(name, out var orte)) namen[name] = orte = new List<string>();
                    orte.Add(asm.Name);
                }
            }
            foreach (var kv in namen.Where(kv => kv.Value.Count > 1))
                context.ReportDiagnostic(Diagnostic.Create(Kollision, Location.None, kv.Key, string.Join(", ", kv.Value)));

            var sb = new StringBuilder();
            sb.AppendLine("// <auto-generated/> ProzessVerbundGenerator — die Prozess-Registries aller Domänen-Assemblies (docs/07).");
            sb.AppendLine("#nullable enable");
            sb.AppendLine("namespace Infrastructure.Prozess");
            sb.AppendLine("{");
            sb.AppendLine("    public static class GeneratedProzessVerbund");
            sb.AppendLine("    {");
            sb.AppendLine("        /// <summary>Prozess-/Fluss-Name → Regeln, über alle Domänen-Assemblies (Namen eindeutig: CQRS012).</summary>");
            sb.AppendLine("        public static readonly global::System.Collections.Generic.IReadOnlyDictionary<string, global::Abstractions.ProzessRegeln> Alle = Vereine();");
            sb.AppendLine();
            sb.AppendLine("        private static global::System.Collections.Generic.Dictionary<string, global::Abstractions.ProzessRegeln> Vereine()");
            sb.AppendLine("        {");
            sb.AppendLine("            var alle = new global::System.Collections.Generic.Dictionary<string, global::Abstractions.ProzessRegeln>();");
            foreach (var r in registries)
                sb.AppendLine($"            foreach (var kv in {r}.Alle) alle.Add(kv.Key, kv.Value);");
            sb.AppendLine("            return alle;");
            sb.AppendLine("        }");
            sb.AppendLine("    }");
            sb.AppendLine("}");
            context.AddSource("GeneratedProzessVerbund.g.cs", sb.ToString());
        }

        /// <summary>Der Prozess-Name: <c>[ProzessName("…")]</c>, sonst der Klassenname (wie im <c>ProzessRegelnGenerator</c>).</summary>
        private static string Name(INamedTypeSymbol def)
        {
            var attr = def.GetAttributes().FirstOrDefault(a => a.AttributeClass?.ToDisplayString() == "Abstractions.ProzessNameAttribute");
            return attr != null && attr.ConstructorArguments.Length > 0 && attr.ConstructorArguments[0].Value is string s && !string.IsNullOrWhiteSpace(s)
                ? s : def.Name;
        }

        private static void Sammle(INamespaceSymbol ns, IAssemblySymbol asm, List<INamedTypeSymbol> aus)
        {
            foreach (var t in ns.GetTypeMembers())
                if (SymbolEqualityComparer.Default.Equals(t.ContainingAssembly, asm)) aus.Add(t);
            foreach (var u in ns.GetNamespaceMembers()) Sammle(u, asm, aus);
        }
    }
}
