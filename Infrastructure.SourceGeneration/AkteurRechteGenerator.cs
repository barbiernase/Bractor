using Microsoft.CodeAnalysis;
using System.Collections.Generic;
using System.Linq;
using System.Text;

namespace Infrastructure.SourceGeneration
{
    /// <summary>
    /// Akteure (<c>docs/konzept-akteure.md</c>): erzeugt <c>GeneratedAkteurRechte</c> — je <c>IAkteur</c>-Record seine Befugnisse, reflexionsfrei als
    /// Tabelle, alles aus der Basisliste (die eine Lesart <see cref="Clientvertragslesart.LiesAkteur"/>): was er hineingibt (<c>IDarf&lt;T&gt;</c>,
    /// nach Art: Command, Query, Hinweis) und was er hört (<c>IHoert</c> eines Events oder Hinweises).
    /// <para><b>Clients</b> (<c>GeneratedClientVertraege</c>, docs/konzept-akteure.md §4): je <c>IClient</c>-Record die verkörperten Akteure
    /// (<c>IVerkoerpert</c>) und der Client-Hash (<c>Abstractions.Clientvertragsregeln</c>), gegen den der Handshake prüft.</para>
    /// </summary>
    [Generator]
    public class AkteurRechteGenerator : ISourceGenerator
    {
        private static readonly DiagnosticDescriptor NameKollision = new DiagnosticDescriptor(
            id: "CQRS059",
            title: "Zwei Akteure/Clients mit gleichem Namen",
            messageFormat: "Der Name '{0}' ist mehrdeutig ({1}) — Composition Root und Handshake ordnen Akteure und Clients über den "
                + "einfachen Namen zu. Benenne einen um.",
            category: "CQRS.Akteur",
            defaultSeverity: DiagnosticSeverity.Error,
            isEnabledByDefault: true);

        public void Initialize(GeneratorInitializationContext context) { }

        public void Execute(GeneratorExecutionContext context)
        {
            if (!Laufzeitprojekt.Ist(context.Compilation)) return;   // nur in der Komposition (docs/07)
            var c = context.Compilation;
            var iAkteur = c.GetTypeByMetadataName(Clientvertragslesart.IAkteur);
            if (iAkteur == null) return;
            var iClient = c.GetTypeByMetadataName(Clientvertragslesart.IClient);
            var fq = SymbolDisplayFormat.FullyQualifiedFormat;

            var alle = new List<INamedTypeSymbol>();
            CollectTypes(c.GlobalNamespace, alle);

            // Akteur = ein Record/eine Klasse mit IAkteur (Domänen-Experte), Client = ein Record mit IClient; Interfaces zählen nicht.
            var akteure = alle.Where(t => Implementiert(t, iAkteur)).OrderBy(t => t.Name, System.StringComparer.Ordinal).ToList();
            var clients = alle.Where(t => Clientvertragslesart.IstClient(t, iClient)).OrderBy(t => t.Name, System.StringComparer.Ordinal).ToList();
            foreach (var g in akteure.Concat(clients).GroupBy(a => a.Name).Where(g => g.Count() > 1))
                context.ReportDiagnostic(Diagnostic.Create(NameKollision, g.First().Locations.FirstOrDefault() ?? Location.None,
                    g.Key, string.Join(", ", g.Select(a => a.ToDisplayString(fq)))));

            var sb = new StringBuilder();
            sb.AppendLine("// <auto-generated/>");
            sb.AppendLine("// Akteure: IDarf<T> und IHoert<T> aus der Basisliste (docs/konzept-akteure.md).");
            sb.AppendLine("using System;");
            sb.AppendLine("using System.Collections.Generic;");
            sb.AppendLine();
            sb.AppendLine("namespace Infrastructure.Akteure;");
            sb.AppendLine();
            sb.AppendLine("public static class GeneratedAkteurRechte");
            sb.AppendLine("{");
            sb.AppendLine("    /// <summary>Akteur-Name (einfacher Typname) → Befugnisse.</summary>");
            sb.AppendLine("    public static IReadOnlyDictionary<string, AkteurRechte> Alle { get; } = new Dictionary<string, AkteurRechte>(StringComparer.Ordinal)");
            sb.AppendLine("    {");
            foreach (var a in akteure.GroupBy(x => x.Name).Select(g => g.First()))
            {
                var g = Clientvertragslesart.LiesAkteur(a);
                bool Hinweis(INamedTypeSymbol t) => t.AllInterfaces.Any(i => i.ToDisplayString() == "Abstractions.ITransientEvent");
                sb.AppendLine($"        [\"{a.Name}\"] = new AkteurRechte(\"{a.Name}\", typeof({a.ToDisplayString(fq)}),");
                sb.AppendLine($"            Commands: {Menge(g.Sendet.Where(t => !Hinweis(t)).Select(t => t.ToDisplayString(fq)))},");
                sb.AppendLine($"            Queries: {Menge(g.Fragt.Select(t => t.ToDisplayString(fq)))},");
                sb.AppendLine($"            TransientEvents: {Menge(g.Sendet.Where(Hinweis).Select(t => t.ToDisplayString(fq)))},");
                sb.AppendLine($"            Hoert: {Menge(g.Kenntnis.Select(t => t.ToDisplayString(fq)))}),");
            }
            sb.AppendLine("    };");
            sb.AppendLine("}");
            context.AddSource("GeneratedAkteurRechte.g.cs", sb.ToString());
            context.AddSource("GeneratedClientVertraege.g.cs", ClientTabelle(c, clients, fq));
        }

        /// <summary><c>GeneratedClientVertraege</c>: je <c>IClient</c>-Record die verkörperten Akteure und der Client-Hash.</summary>
        private static string ClientTabelle(Compilation c, List<INamedTypeSymbol> clients, SymbolDisplayFormat fq)
        {
            var sb = new StringBuilder();
            sb.AppendLine("// <auto-generated/>");
            sb.AppendLine("// Clients: wen eine Software an der Leitung verkörpert (docs/konzept-akteure.md §4).");
            sb.AppendLine("using System;");
            sb.AppendLine("using System.Collections.Generic;");
            sb.AppendLine();
            sb.AppendLine("namespace Infrastructure.Akteure;");
            sb.AppendLine();
            sb.AppendLine("public static class GeneratedClientVertraege");
            sb.AppendLine("{");
            sb.AppendLine("    /// <summary>Client-Name (Record-Name) → Client.</summary>");
            sb.AppendLine("    public static IReadOnlyDictionary<string, ClientVertrag> Alle { get; } = new Dictionary<string, ClientVertrag>(StringComparer.Ordinal)");
            sb.AppendLine("    {");
            foreach (var cl in clients.GroupBy(x => x.Name).Select(g => g.First()))
            {
                var v = Clientvertragslesart.Lies(cl, c);
                sb.AppendLine($"        [\"{v.Name}\"] = new ClientVertrag(\"{v.Name}\", typeof({cl.ToDisplayString(fq)}), \"{v.Hash}\",");
                sb.AppendLine($"            Verkoerpert: new[] {{ {string.Join(", ", v.Akteure.Select(a => $"\"{a.Name}\""))} }}),");
            }
            sb.AppendLine("    };");
            sb.AppendLine("}");
            return sb.ToString();
        }

        private static string Menge(IEnumerable<string> typen)
        {
            var liste = typen.OrderBy(x => x, System.StringComparer.Ordinal).ToList();
            return liste.Count == 0
                ? "new HashSet<Type>()"
                : "new HashSet<Type> { " + string.Join(", ", liste.Select(t => $"typeof({t})")) + " }";
        }

        private static bool Implementiert(INamedTypeSymbol t, INamedTypeSymbol? iface) => Clientvertragslesart.Implementiert(t, iface);

        private static void CollectTypes(INamespaceSymbol ns, List<INamedTypeSymbol> results)
        {
            foreach (var type in ns.GetTypeMembers())
                CollectNested(type, results);
            foreach (var sub in ns.GetNamespaceMembers())
                CollectTypes(sub, results);
        }

        private static void CollectNested(INamedTypeSymbol type, List<INamedTypeSymbol> results)
        {
            if (type.TypeKind == TypeKind.Class && !type.IsAbstract)
                results.Add(type);
            foreach (var nested in type.GetTypeMembers())
                CollectNested(nested, results);
        }
    }
}
