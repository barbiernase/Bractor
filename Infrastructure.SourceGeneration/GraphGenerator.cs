using Microsoft.CodeAnalysis;
using System.Linq;
using System.Text;

namespace Infrastructure.SourceGeneration
{
    /// <summary>
    /// Graphen (docs/04 §4.4): erzeugt <c>GeneratedGraphen</c> — je Graph seine Knoten (aufgefaltet, Name → Funktion), je Knoten seine Operationen (das
    /// <c>Auf</c>, die Ports mit Form und Erzeugern, was sie ausgibt, was als Strom, die Ebene) und die Köpfe (Eingangstyp → Knoten). Alles NUR aus dem
    /// Record und den Signaturen seiner Funktionen (<see cref="Graphform"/>); einen Graphen mit Formfehler meldet CQRS115 im Pipeline-Projekt, hier fehlt er.
    /// </summary>
    [Generator]
    public class GraphGenerator : ISourceGenerator
    {
        public void Initialize(GeneratorInitializationContext context) { }

        public void Execute(GeneratorExecutionContext context)
        {
            if (!Laufzeitprojekt.Ist(context.Compilation)) return;   // nur in der Komposition (docs/07)
            var c = context.Compilation;
            if (c.GetTypeByMetadataName(Graphform.IGraph) == null) return;
            var fq = SymbolDisplayFormat.FullyQualifiedFormat;
            string T(ITypeSymbol t) => t.ToDisplayString(fq);
            string S(string s) => "\"" + s.Replace("\\", "\\\\").Replace("\"", "\\\"") + "\"";
            string Typen(System.Collections.Generic.IEnumerable<ITypeSymbol> ts) =>
                $"new Type[] {{ {string.Join(", ", ts.Select(T).Distinct().OrderBy(x => x, System.StringComparer.Ordinal).Select(x => $"typeof({x})"))} }}";

            var graphen = Vertragsassemblies.Typen(c).Where(Graphform.IstGraph).OrderBy(t => t.Name, System.StringComparer.Ordinal)
                .Select(Graphform.Lies).Where(g => g.Fehler.Count == 0).ToList();

            var sb = new StringBuilder();
            sb.AppendLine("// <auto-generated/>");
            sb.AppendLine("// Graphen: Knoten, Operationen, Ports mit Erzeugern, Köpfe (GraphGenerator). Nicht editieren.");
            sb.AppendLine("#nullable enable");
            sb.AppendLine("using System;");
            sb.AppendLine("using System.Collections.Generic;");
            sb.AppendLine();
            sb.AppendLine("namespace Infrastructure.Funktionen");
            sb.AppendLine("{");
            sb.AppendLine("    public static class GeneratedGraphen");
            sb.AppendLine("    {");
            sb.AppendLine("        /// <summary>Alle Graphen der Anwendung (Blaupausen; laufen erst als Instanz).</summary>");
            sb.AppendLine("        public static readonly IReadOnlyList<GraphPlan> Alle = new GraphPlan[]");
            sb.AppendLine("        {");
            foreach (var g in graphen)
            {
                sb.AppendLine($"            new GraphPlan({S(g.Typ.Name)}, typeof({T(g.Typ)}),");
                sb.AppendLine("                new KnotenPlan[]");
                sb.AppendLine("                {");
                foreach (var k in g.Knoten)
                {
                    sb.AppendLine($"                    new KnotenPlan({S(k.Name)}, {S(Funktionsform.Anzeigename(k.Typ))}, new OperationPlan[]");
                    sb.AppendLine("                    {");
                    foreach (var op in k.Operationen)
                    {
                        var ports = op.Auf.Ports.Select(p =>
                        {
                            var erzeuger = g.Kanten.Where(e => e.NachOperation == op && e.Port == p)
                                .Select(e => $"new ErzeugerPlan({S(e.Von.Name)}, {e.VonOperation.Nummer}, typeof({T(e.Typ)}), {(e.Strom ? "true" : "false")})");
                            return $"new PortPlan({S(p.Name)}, Portform.{p.Form}, {Typen(p.Typen)}, new ErzeugerPlan[] {{ {string.Join(", ", erzeuger)} }})";
                        });
                        var stroeme = op.Ausgaben.Where(x => op.Stroeme.Contains(Funktionsform.Voll(x)));
                        sb.AppendLine($"                        new OperationPlan({op.Nummer}, new PortPlan[] {{ {string.Join(", ", ports)} }}, {Typen(op.Ausgaben)}, "
                            + $"{Typen(stroeme)}, new string[] {{ {string.Join(", ", op.Ebene.Select(S))} }}),");
                    }
                    sb.AppendLine("                    }),");
                }
                sb.AppendLine("                },");
                var koepfe = g.Koepfe.OrderBy(x => T(x.Typ), System.StringComparer.Ordinal)
                    .Select(x => $"[typeof({T(x.Typ)})] = new[] {{ {string.Join(", ", x.Knoten.Select(k => S(k.Name)))} }}");
                sb.AppendLine($"                new Dictionary<Type, string[]> {{ {string.Join(", ", koepfe)} }},");
                sb.AppendLine($"                {Typen(g.Ausgaenge.Select(x => (ITypeSymbol)x.Typ))}, Quelle: {(g.Quelle != null ? S(g.Quelle.Name) : "null")}),");
            }
            sb.AppendLine("        };");
            sb.AppendLine("    }");
            sb.AppendLine("}");
            context.AddSource("GeneratedGraphen.g.cs", sb.ToString());
        }
    }
}
