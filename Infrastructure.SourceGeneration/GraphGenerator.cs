using Microsoft.CodeAnalysis;
using System.Linq;
using System.Text;

namespace Infrastructure.SourceGeneration
{
    /// <summary>
    /// Graphen (docs/04 §4.4): erzeugt <c>GeneratedGraphen</c> — je Graph seine Knoten (Name → Funktion), je Knoten die Kanten (Command ohne Ziel → die
    /// Knoten desselben Graphen, die ihn nehmen) und die Köpfe (Eingangstyp → Knoten). Alles NUR aus dem Record und den Signaturen seiner Funktionen
    /// (<see cref="Graphform"/>); einen Graphen mit Formfehler meldet CQRS115 im Pipeline-Projekt, hier fehlt er.
    /// </summary>
    [Generator]
    public class GraphGenerator : ISourceGenerator
    {
        public void Initialize(GeneratorInitializationContext context) { }

        public void Execute(GeneratorExecutionContext context)
        {
            if (!Laufzeitprojekt.Ist(context.Compilation)) return;   // nur in der Komposition (docs/07)
            var c = context.Compilation;
            if (c.GetTypeByMetadataName(Graphform.IGraph) == null) return;
            var fq = SymbolDisplayFormat.FullyQualifiedFormat;
            string T(ITypeSymbol t) => t.ToDisplayString(fq);

            var graphen = Vertragsassemblies.Typen(c).Where(Graphform.IstGraph).OrderBy(t => t.Name, System.StringComparer.Ordinal)
                .Select(Graphform.Lies).Where(g => g.Fehler.Count == 0).ToList();

            var sb = new StringBuilder();
            sb.AppendLine("// <auto-generated/>");
            sb.AppendLine("// Graphen: Knoten, Kanten, Köpfe (GraphGenerator). Nicht editieren.");
            sb.AppendLine("#nullable enable");
            sb.AppendLine("using System;");
            sb.AppendLine("using System.Collections.Generic;");
            sb.AppendLine();
            sb.AppendLine("namespace Infrastructure.Funktionen");
            sb.AppendLine("{");
            sb.AppendLine("    public static class GeneratedGraphen");
            sb.AppendLine("    {");
            sb.AppendLine("        /// <summary>Alle Graphen der Anwendung (Blaupausen; laufen erst als Instanz).</summary>");
            sb.AppendLine("        public static readonly IReadOnlyList<GraphPlan> Alle = new GraphPlan[]");
            sb.AppendLine("        {");
            foreach (var g in graphen)
            {
                sb.AppendLine($"            new GraphPlan(\"{g.Typ.Name}\", typeof({T(g.Typ)}),");
                sb.AppendLine("                new KnotenPlan[]");
                sb.AppendLine("                {");
                foreach (var k in g.Knoten)
                {
                    var kanten = g.Kanten.Where(e => e.Von == k).GroupBy(e => T(e.Typ)).OrderBy(x => x.Key, System.StringComparer.Ordinal)
                        .Select(x => $"[typeof({x.Key})] = new[] {{ {string.Join(", ", x.Select(e => "\"" + e.Nach.Name + "\""))} }}");
                    sb.AppendLine($"                    new KnotenPlan(\"{k.Name}\", \"{k.Typ.Name}\", new Dictionary<Type, string[]> {{ {string.Join(", ", kanten)} }}),");
                }
                sb.AppendLine("                },");
                var koepfe = g.Koepfe.OrderBy(x => T(x.Typ), System.StringComparer.Ordinal)
                    .Select(x => $"[typeof({T(x.Typ)})] = new[] {{ {string.Join(", ", x.Knoten.Select(k => "\"" + k.Name + "\""))} }}");
                sb.AppendLine($"                new Dictionary<Type, string[]> {{ {string.Join(", ", koepfe)} }},");
                var aus = g.Ausgaenge.Select(x => T(x.Typ)).Distinct().OrderBy(x => x, System.StringComparer.Ordinal).Select(x => $"typeof({x})");
                sb.AppendLine($"                new Type[] {{ {string.Join(", ", aus)} }}),");
            }
            sb.AppendLine("        };");
            sb.AppendLine("    }");
            sb.AppendLine("}");
            context.AddSource("GeneratedGraphen.g.cs", sb.ToString());
        }
    }
}
